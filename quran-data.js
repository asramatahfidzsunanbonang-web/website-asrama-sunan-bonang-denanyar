// Target hafalan program Binnadzor: Juz 28, 29, 30
const BINNADZOR_TARGET_JUZ = [28, 29, 30];

// Helper untuk mendapatkan surat berdasarkan juz
function getSurahsByJuz(juzNo) {
  return QURAN_SURAHS.filter(s => s.juz === Number(juzNo));
}

// Helper untuk mendapatkan surat Binnadzor (Juz 28, 29, 30)
function getBinnadzorSurahs() {
  return QURAN_SURAHS.filter(s => BINNADZOR_TARGET_JUZ.includes(s.juz));
}

